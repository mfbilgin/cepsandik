export type TranslationKey = keyof typeof dictionaries.tr;

export const translate = (
    language: Language,
    key: TranslationKey,
    params?: TranslationParams,
): string => {
    const raw = dictionaries[language][key] ?? dictionaries.tr[key] ?? key;
    const withParams = params
        ? Object.entries(params).reduce(
            (message, [paramKey, value]) => message.replaceAll(`{${paramKey}}`, String(value)),
            raw,
        )
        : raw;

    return withParams;
};
